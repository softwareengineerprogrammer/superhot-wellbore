# ALL AT ONCE
# ====================================================================

def export_all(profile, output_directory, name=None,
               profile_temperature='wellhead', extra=None):
    """
    Write the profile, the input deck and the JSON result.

    Parameters
    ----------
    profile : ProductionProfile
        Result of SuperhotWellboreClient.solve_profile().
    output_directory : str
        Directory to write into; created if missing.
    name : str or None
        File name stem. Defaults to the request name.
    profile_temperature : str
        'wellhead' or 'feedzone', see results.py.
    extra : dict or None
        Additional GEOPHIRES parameters for the deck.

    Returns
    -------
    dict
        Keys 'temperature_profile', 'geophires_input' and
        'profile_json', each holding the path written.
    """
    stem = name or getattr(profile.request, 'name', None) or 'superhot'
    os.makedirs(output_directory, exist_ok=True)

    profile_name = f'{stem}_reservoir_temperature.csv'
    paths = {
        'temperature_profile': write_temperature_profile(
            profile, os.path.join(output_directory, profile_name),
            profile_temperature=profile_temperature),
        'geophires_input': write_geophires_input(
            profile,
            os.path.join(output_directory, f'{stem}_geophires.txt'),
            reservoir_output_file=profile_name,
            profile_temperature=profile_temperature, extra=extra),
        'profile_json': write_profile_json(
            profile,
            os.path.join(output_directory, f'{stem}_profile.json')),
    }
    return paths


# ====================================================================
# INTERNAL
# ====================================================================

def _write_lines(path, lines):
    """Write lines to path, creating the parent directory if needed."""
    directory = os.path.dirname(os.path.abspath(path))
    if directory:
        os.makedirs(directory, exist_ok=True)
    with open(path, 'w', encoding='utf-8') as handle:
        handle.write('\n'.join(lines) + '\n')
