def write_profile_json(profile, path):
    """Write the complete client result as JSON. Returns the path."""
    directory = os.path.dirname(os.path.abspath(path))
    if directory:
        os.makedirs(directory, exist_ok=True)
    with open(path, 'w', encoding='utf-8') as handle:
        json.dump(profile.to_dict(), handle, indent=2)
        handle.write('\n')
    return path


def write_request_json(request, path):
    """Write a request as JSON. Returns the path."""
    directory = os.path.dirname(os.path.abspath(path))
    if directory:
        os.makedirs(directory, exist_ok=True)
    with open(path, 'w', encoding='utf-8') as handle:
        json.dump(request.to_dict(), handle, indent=2)
        handle.write('\n')
    return path


