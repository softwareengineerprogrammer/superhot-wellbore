def geophires_input_text(profile, reservoir_output_file,
                         profile_temperature='wellhead', extra=None):
    """
    Build the text of a GEOPHIRES input deck fragment.

    Parameters
    ----------
    profile : ProductionProfile
        Result of SuperhotWellboreClient.solve_profile().
    reservoir_output_file : str
        Value for 'Reservoir Output File Name'. GEOPHIRES resolves it
        relative to its own working directory, so a bare file name
        works when the deck and the profile sit side by side.
    profile_temperature : str
        Must match the value used for the profile file.
    extra : dict or None
        Additional 'Parameter Name' -> value entries.

    Returns
    -------
    str
        Deck text, ending with a newline.
    """
    if profile_temperature not in PROFILE_TEMPERATURES:
        raise ValueError(f'Unknown profile_temperature '
                         f'{profile_temperature!r}')

    parameters = profile.to_geophires_parameters(
        profile_temperature=profile_temperature, extra=extra)
    parameters['Reservoir Output File Name'] = reservoir_output_file

    summary = profile.summary()
    name = summary.get('name') or 'superhot'

    lines = [
        '# ==================================================='
        '=================',
        f'# GEOPHIRES input parameters for the superhot well '
        f'"{name}"',
        '# Generated by the superhot-wellbore GEOPHIRES client '
        '(superhot_wellbore.client).',
        '#',
        f'# The temperature profile in {reservoir_output_file} holds '
        f'the',
        f'# {profile_temperature} temperature computed by the coupled '
        f'reservoir-wellbore',
        '# model of Ingason-style superhot wells, re-solved along the '
        'declining',
        '# reservoir state described in the accompanying JSON result.',
        '#',
    ]

    for key, value in summary.items():
        if value is not None:
            lines.append(f'#   {key}: {_format_value(value)}')
    if profile.notes:
        lines.append('#')
        for note in profile.notes:
            lines.append(f'#   note: {note}')
    lines.append(
        '# ==================================================='
        '=================')
    lines.append('')

    written = set()
    for key in _PARAMETER_ORDER:
        if key in parameters:
            lines.append(_parameter_line(key, parameters[key]))
            written.add(key)
    for key in sorted(set(parameters) - written):
        lines.append(_parameter_line(key, parameters[key]))

    lines.extend([
        '',
        '-- Surface plant and economic parameters are outside the '
        'scope of the',
        '-- superhot-wellbore model. Add the ones your study needs '
        '(end-use',
        '-- option, power plant type, economic model, capital costs, '
        '...) below,',
        '-- or append this fragment to an existing deck.',
    ])

    return '\n'.join(lines) + '\n'


def _parameter_line(key, value):
    """Render one 'Name, value, comment' deck line."""
    comment = _PARAMETER_COMMENTS.get(key)
    rendered = _format_value(value)
    if comment:
        return f'{key}, {rendered}, {comment}'
    return f'{key}, {rendered}'


def write_geophires_input(profile, path, reservoir_output_file,
                          profile_temperature='wellhead', extra=None):
    """
    Write a GEOPHIRES input deck fragment. Returns the path written.
    """
    text = geophires_input_text(
        profile, reservoir_output_file,
        profile_temperature=profile_temperature, extra=extra)
    _write_lines(path, text.splitlines())
    return path


