# -*- coding: utf-8 -*-
"""
File Exchange With GEOPHIRES
=============================

Writes a production history to the files GEOPHIRES reads, so that a
superhot well can be used as a GEOPHIRES reservoir without changing a
single line of GEOPHIRES code:

    <name>_reservoir_temperature.csv
        Two-column 'time [yr], temperature [C]' profile, the format
        expected by the GEOPHIRES 'User-Provided Temperature Profile'
        reservoir model (Reservoir Model 5) through its
        'Reservoir Output File Name' parameter.

    <name>_geophires.txt
        A GEOPHIRES input deck fragment that selects that reservoir
        model, points at the profile file and carries the well and
        operating parameters derived from the superhot solution
        (flow rate, wellhead pressure, depth, gradient, ...).

    <name>_profile.json
        The complete client result: request, summary, notes, the
        GEOPHIRES parameter mapping and every timestep. This is the
        machine-readable output of the command-line client and is not
        read by GEOPHIRES itself.

GEOPHIRES input decks are line oriented, 'Parameter Name, value,
optional comment', with '#', '--' and '*' starting a comment line
(see geophires_x/GeoPHIRESUtils.read_input_file).

Author: superhot-wellbore GEOPHIRES client
"""

import json
import os

from .results import PROFILE_TEMPERATURES


# ====================================================================
# DECK LAYOUT
# ====================================================================

#: Order in which known parameters are written into the input deck,
#: grouped the way GEOPHIRES examples are laid out.
_PARAMETER_ORDER = (
    'Reservoir Model',
    'Reservoir Output File Name',
    'Plant Lifetime',
    'Time steps per year',
    'Reservoir Depth',
    'Maximum Temperature',
    'Surface Temperature',
    'Gradient 1',
    'Reservoir Hydrostatic Pressure',
    'Number of Production Wells',
    'Number of Injection Wells',
    'Production Well Diameter',
    'Production Flow Rate per Well',
    'Production Wellhead Pressure',
    'Ramey Production Wellbore Model',
    'Production Wellbore Temperature Drop',
)

#: Short explanations written as the third, comment field of each line
_PARAMETER_COMMENTS = {
    'Reservoir Model': 'user-provided temperature profile',
    'Reservoir Output File Name': 'written by the superhot client',
    'Reservoir Depth': 'km, feedzone depth of the superhot well',
    'Maximum Temperature': 'C, raised to admit the superhot reservoir',
    'Gradient 1': 'C/km, average to the feedzone',
    'Reservoir Hydrostatic Pressure': 'kPa, far-field reservoir pressure',
    'Production Flow Rate per Well': 'kg/s, from the coupled model',
    'Production Wellhead Pressure': 'kPa, from the coupled model',
    'Ramey Production Wellbore Model': 'the superhot wellbore model '
                                       'already applied heat loss',
    'Production Wellbore Temperature Drop': 'C, already applied',
}


def _format_value(value):
    """Render a parameter value the way GEOPHIRES parses it."""
    if isinstance(value, bool):
        return 'True' if value else 'False'
    if isinstance(value, int):
        return str(value)
    if isinstance(value, float):
        return f'{value:.6g}'
    return str(value)


# ====================================================================
# PROFILE FILE
# ====================================================================

def write_temperature_profile(profile, path,
                              profile_temperature='wellhead'):
    """
    Write the GEOPHIRES 'Reservoir Output File Name' profile.

    Parameters
    ----------
    profile : ProductionProfile
        Result of SuperhotWellboreClient.solve_profile().
    path : str
        Destination file.
    profile_temperature : str
        'wellhead' or 'feedzone', see results.py.

    Returns
    -------
    str
        The path written.

    Raises
    ------
    ValueError
        If the profile holds no usable timestep.
    """
    rows = profile.temperature_profile_rows(profile_temperature)
    if not rows:
        raise ValueError(
            'The profile contains no successful timestep, so there is '
            'no temperature history to write. Check profile.notes for '
            'the reason.')

    lines = [f'# time [yr], {profile_temperature} temperature [C]',
             '# generated by the superhot-wellbore GEOPHIRES client']
    for time_yr, temperature_C in rows:
        lines.append(f'{time_yr:.6f},{temperature_C:.4f}')

    _write_lines(path, lines)
    return path


